"""Mission data for the fictional astronaut Cmdr A. Nova.

The data is generated by data_gen/generate.py into data/mission_days.json
(calibrated on published NASA figures, real space weather from NASA DONKI).
"""

import json
from functools import lru_cache
from pathlib import Path

DATA_DIR = Path(__file__).resolve().parents[2] / "data"
MISSION_FILE = DATA_DIR / "mission_days.json"


@lru_cache(maxsize=1)
def _load() -> dict:
    if not MISSION_FILE.exists():
        raise RuntimeError(f"{MISSION_FILE} is missing. Run: python3 data_gen/generate.py")
    return json.loads(MISSION_FILE.read_text())


def meta() -> dict:
    return _load()["meta"]


def mission_days() -> tuple[dict, ...]:
    return tuple(_load()["days"])


def get_day(day: int) -> dict | None:
    days = _load()["days"]
    if 1 <= day <= len(days):
        return days[day - 1]
    return None
